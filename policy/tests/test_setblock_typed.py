    def test_mixed_provenance_and_inconsistent_unknowns_rejected(self):
        initial = self.targets()
        self.assertEqual(self.run_cli('--typed-json', self.payload, '--source-root', self.source).returncode, 0)
        path = self.repo / SNAPSHOT
        path.write_bytes(initial[0])
        self.reject(json.dumps([NEUTRAL]).encode(), 'not in lockstep')
        path.write_bytes(initial[0])
        (self.repo / CATALOG).write_bytes(initial[1])
        rows = json.loads(path.read_text())
        next(r for r in rows if r.get('record_id') == RID)['unknowns'].append('one sided')
        path.write_text(json.dumps(rows))
        self.reject(json.dumps([NEUTRAL]).encode(), 'not in lockstep')

    def test_source_bytes_required_and_validated(self):
        source = Path(self.tmp.name) / 'source'
        shutil.copytree(self.source, source)
        self.source = source
        installed = source / 'usr/share/rpcd/ucode/luci'
        installed.write_bytes(installed.read_bytes() + b'\n')
        self.reject(json.dumps([NEUTRAL]).encode(), 'source bytes')
        installed.unlink()
        self.reject(json.dumps([NEUTRAL]).encode())

    def test_required_lists_and_unknowns_cannot_be_weakened(self):
        for key in ('conditions', 'assumptions', 'evidence_refs', 'unknowns'):
            for index in range(len(NEUTRAL[key])):
                record = copy.deepcopy(NEUTRAL)
                record[key].pop(index)
                with self.subTest(key=key, removed=index):
                    self.reject(json.dumps([record]).encode(), 'supported family')
            record = copy.deepcopy(NEUTRAL)
            record[key].append(record[key][0])
            self.reject(json.dumps([record]).encode(), 'supported family')
        for key in ('conditions', 'assumptions', 'evidence_refs'):
            record = copy.deepcopy(NEUTRAL)
            record[key].reverse()
            self.reject(json.dumps([record]).encode(), 'supported family')

    def test_policy_mutations_fail_closed(self):
        path = self.repo / 'policy/grants.json'
        original = path.read_bytes()
        for session in ('root', 'luci-mod-system-mounts'):
            for field in ('record_type', 'evidence_status', 'producer', 'assessment', 'expectation_id',
                          'target_id', 'op', 'corpus_revision', 'profile', 'ingress', 'entrypoint_id',
                          'ubus_object', 'method', 'session_class'):
                with self.subTest(session=session, field=field):
                    rows = json.loads(original)
                    grant = next(r for r in rows if r.get('record_id') == f'policy:grant:{session}:ubus_http:luci.setBlockDetect')
                    grant[field] = 'changed'
                    path.write_text(json.dumps(rows))
                    self.reject(json.dumps([NEUTRAL]).encode(), 'mismatched grant')
        path.write_bytes(original)
        decisions = self.repo / 'policy/policy_decisions.json'
        original = decisions.read_bytes()
        rows = json.loads(original)
        rows['decisions'] = [r for r in rows['decisions'] if r.get('record_id') != 'policy:decision:unauthenticated-setBlockDetect-deny']
        decisions.write_text(json.dumps(rows))
        self.reject(json.dumps([NEUTRAL]).encode(), 'deny decision')
        decisions.write_bytes(original)
        expectations = self.repo / 'corpus/profiles/luci-ssl-25.12/expected-capabilities.json'
        original = expectations.read_bytes()
        rows = json.loads(original)
        rows['expectations'] = [r for r in rows['expectations'] if r.get('expectation_id') != 'luci-mod-system-mounts']
        expectations.write_text(json.dumps(rows))
        self.reject(json.dumps([NEUTRAL]).encode(), 'mounts expectation')
        expectations.write_bytes(original)

    def test_typed_transaction_rolls_back_second_replace_failure(self):
        before = self.targets()
        real = os.replace
        calls = []
        def fail_second(src, dst):
            calls.append((src, dst))
            if len(calls) == 2:
                raise OSError('injected failure')
            return real(src, dst)
        with patch('policy.setblock_table.os.replace', side_effect=fail_second):
            with self.assertRaisesRegex(OSError, 'injected failure'):
                import_typed(self.payload, self.source, self.repo)
        self.assertEqual([Path(dst) for _, dst in calls], [self.repo / SNAPSHOT, self.repo / CATALOG, self.repo / SNAPSHOT])
        self.assertEqual(before, self.targets())
        self.assertFalse(list((self.repo / 'reports').glob('.setblock-*')))

    def test_cli_rejects_invalid_or_ambiguous_input(self):
        before = self.targets()
        for args in ([], ['--source-root', self.source], ['--typed-json', self.payload],
                     ['--source-root', self.source, '--typed-json', self.payload, '--csv', self.payload]):
            self.assertNotEqual(self.run_cli(*args).returncode, 0)
            self.assertEqual(before, self.targets())
        for raw in (b'', b'\xff', b'[]', b'[{"record_id":"bad","record_id":"bad"}]'):
            with self.subTest(raw=raw):
                self.payload.write_bytes(raw)
                proc = self.run_cli('--typed-json', self.payload, '--source-root', self.source)
                self.assertNotEqual(proc.returncode, 0)
                self.assertEqual(before, self.targets())
