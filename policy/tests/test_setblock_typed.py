class TypedCLI(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Path(self.tmp.name) / 'repo'
        for item in ('policy', 'corpus', 'reports'):
            shutil.copytree(ROOT / item, self.repo / item, ignore=shutil.ignore_patterns('__pycache__'))
        self.source = ROOT / 'policy/fixtures/getblock-source'
        self.payload = Path(self.tmp.name) / 'input.json'
        self.payload.write_text(json.dumps([NEUTRAL]), encoding='utf-8')

    def run_cli(self, *args):
        return subprocess.run([sys.executable, '-B', '-m', 'policy.setblock_table', *map(str, args)],
                              cwd=self.repo, capture_output=True)

    def targets(self):
        return tuple((self.repo / p).read_bytes() for p in (SNAPSHOT, CATALOG))

    def protected(self):
        paths = (SNAPSHOT, CATALOG, Path('policy/grants.json'), Path('policy/policy_decisions.json'),
                 Path('corpus/lock.json'), Path('corpus/profiles/luci-ssl-25.12/expected-capabilities.json'))
        return tuple((self.repo / p).read_bytes() for p in paths)

    def test_csv_prestate_to_typed_and_byte_idempotent(self):
        before = self.targets()
        protected = self.protected()[2:]
        unrelated = [[r for r in json.loads(data) if r.get('record_id') != RID] for data in before]
        proc = self.run_cli('--typed-json', self.payload, '--source-root', self.source)
        self.assertEqual(proc.returncode, 0, proc.stderr.decode())
        self.assertNotEqual(before, self.targets())
        grants = json.loads((self.repo / 'policy/grants.json').read_text())
        for index, data in enumerate(self.targets()):
            rows = json.loads(data)
            self.assertEqual(json.dumps([r for r in rows if r.get('record_id') != RID], sort_keys=True),
                             json.dumps(unrelated[index], sort_keys=True))
            target = next(r for r in rows if r.get('record_id') == RID)
            self.assertEqual(target['analysis_revision'], 'step3:setblock-typed-import-v1')
            self.assertEqual(sum(r.get('record_id') == RID for r in rows), 1)
            self.assertEqual(next(i for i, r in enumerate(rows) if r.get('record_id') == RID), (1, 13)[index])
            self.assertEqual(json.dumps(target, sort_keys=True), json.dumps(RETAINED, sort_keys=True))
            self.assertEqual(target['assessment'], 'intended_access')
            self.assertEqual(target['expectation_id'], 'luci-mod-system-mounts')
            primary, supplementary = join_policy_grants(target, {g['record_id']: g for g in grants}, scope='aggregate')
            self.assertEqual([g['record_id'] for g in primary], ['policy:grant:luci-mod-system-mounts:ubus_http:luci.setBlockDetect'])
            self.assertEqual([g['record_id'] for g in supplementary], ['policy:grant:root:ubus_http:luci.setBlockDetect'])
        self.assertEqual(protected, self.protected()[2:])
        once = self.targets()
        proc = self.run_cli('--typed-json', self.payload, '--source-root', self.source)
        self.assertEqual(proc.returncode, 0, proc.stderr.decode())
        self.assertEqual(once, self.targets())

    def reject(self, raw, message=None):
        self.payload.write_bytes(raw)
        before = self.protected()
        with patch('policy.setblock_table.os.replace') as replace:
            with self.assertRaises((ValueError, OSError, UnicodeError)) as raised:
                import_typed(self.payload, self.source, self.repo)
        if message:
            self.assertIn(message, str(raised.exception))
        replace.assert_not_called()
        self.assertEqual(before, self.protected())
        self.assertFalse(list((self.repo / 'reports').glob('.setblock-*')))

    def test_malformed_and_duplicate_key_payloads_fail_closed(self):
        for raw in (b'', b'null', b'{}', b'[]', b'[null]', b'1', b'\xff', b'[', b'[] trailing',
                    json.dumps([NEUTRAL, NEUTRAL]).encode(), b'[NaN]'):
            with self.subTest(raw=raw[:32]):
                self.reject(raw)
        raw = json.dumps([NEUTRAL])
        for key in ('record_id', 'assessment', 'analysis_revision', 'start_line', 'path'):
            needle = json.dumps(key) + ': '
            with self.subTest(key=key):
                # Equal duplicates are forbidden too, not merely conflicting ones.
                value = NEUTRAL['source_location'][key] if key in NEUTRAL['source_location'] else NEUTRAL[key]
                self.reject(raw.replace(needle, needle + json.dumps(value) + ', ' + needle, 1).encode(), 'duplicate JSON key')

    def test_every_field_is_closed_and_type_sensitive(self):
        for field in NEUTRAL:
            for variation in ('missing', 'changed'):
                with self.subTest(field=field, variation=variation):
                    record = copy.deepcopy(NEUTRAL)
                    if variation == 'missing':
                        del record[field]
                    elif field == 'unknowns':
                        record[field] = record[field][1:]
                    else:
                        record[field] = False
                    self.reject(json.dumps([record]).encode(), 'supported family')
        for field in ('start_line', 'start_column', 'end_line', 'end_column'):
            for value in (float(NEUTRAL['source_location'][field]), True, str(NEUTRAL['source_location'][field]), None):
                with self.subTest(field=field, value=value):
                    record = copy.deepcopy(NEUTRAL)
                    record['source_location'][field] = value
                    self.reject(json.dumps([record]).encode(), 'supported family')
        for field, value in [('session_class', 'root'), ('expectation_id', None), ('coverage', {}),
                             ('executed', True), ('primary_grants', [])]:
            record = copy.deepcopy(NEUTRAL)
            record[field] = value
            self.reject(json.dumps([record]).encode(), 'supported family')
        record = copy.deepcopy(NEUTRAL)
        record['source_location']['extra'] = 1
        self.reject(json.dumps([record]).encode(), 'supported family')
        for value in ('intended_access', 'risky_delegation', 'authorization_violation'):
            record = copy.deepcopy(NEUTRAL)
            record['assessment'] = value
            self.reject(json.dumps([record]).encode(), 'supported family')
        record = copy.deepcopy(NEUTRAL)
        record['evidence_refs'].append('policy:grant:root:ubus_http:luci.setBlockDetect')
        self.reject(json.dumps([record]).encode(), 'supported family')

    def test_legacy_transition_merges_unknowns_and_reimport_and_rejects_downgrade(self):
        legacy = json.loads((ROOT / 'policy/fixtures/setblock-legacy-effects.json').read_text())
        for artifact, key in ((SNAPSHOT, 'snapshot_effect'), (CATALOG, 'catalog_effect')):
            path = self.repo / artifact
            rows = json.loads(path.read_text())
            row = copy.deepcopy(legacy[key])
            row['unknowns'].append('prestate extra uncertainty')
            path.write_text(json.dumps([row if r.get('record_id') == RID else r for r in rows]))
        record = copy.deepcopy(NEUTRAL)
        record['unknowns'].append('producer extra uncertainty')
        self.payload.write_text(json.dumps([record]))
        self.assertEqual(self.run_cli('--typed-json', self.payload, '--source-root', self.source).returncode, 0)
        for data in self.targets():
            target = next(r for r in json.loads(data) if r.get('record_id') == RID)
            self.assertEqual(target['analysis_revision'], 'step3:setblock-typed-import-v1')
            self.assertEqual(target['unknowns'], NEUTRAL['unknowns'] + ['prestate extra uncertainty', 'producer extra uncertainty'])
        once = self.targets()
        self.assertEqual(self.run_cli('--typed-json', self.payload, '--source-root', self.source).returncode, 0)
        self.assertEqual(once, self.targets())
        proc = self.run_cli('--csv', ROOT / 'policy/fixtures/setblock-observation.csv', '--source-root', self.source)
        self.assertNotEqual(proc.returncode, 0)
        self.assertEqual(once, self.targets())
        self.reject(b'[]')

    def test_typed_context_and_pair_rejections(self):
        for artifact in (SNAPSHOT, CATALOG):
            path = self.repo / artifact
            original = path.read_bytes()
            rows = json.loads(original)
            target = next(r for r in rows if r.get('record_id') == RID)
            target['source_location']['start_line'] = 532.0
            path.write_text(json.dumps(rows))
            self.reject(json.dumps([NEUTRAL]).encode(), 'source location')
            path.write_bytes(original)
            rows = json.loads(original)
            rows.append({'record_id': 'alias', 'effect_id': 'setBlockDetect.block-detect.system'})
            path.write_text(json.dumps(rows))
            self.reject(json.dumps([NEUTRAL]).encode(), 'effect identity')
            path.write_bytes(original)
        lock = self.repo / 'corpus/lock.json'
        original = lock.read_bytes()
        lock.write_bytes(original + b'\n')
        self.reject(json.dumps([NEUTRAL]).encode(), 'supported family')
        lock.write_bytes(original)

    def test_csv_downgrade_from_canonical_typed_state_is_rejected(self):
        proc = self.run_cli('--typed-json', self.payload, '--source-root', self.source)
        self.assertEqual(proc.returncode, 0, proc.stderr.decode())
        before = self.targets()
        proc = self.run_cli('--csv', ROOT / 'policy/fixtures/setblock-observation.csv', '--source-root', self.source)
        self.assertNotEqual(proc.returncode, 0)
